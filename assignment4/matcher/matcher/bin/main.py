def save_results(comparisons, output_path):
    """Save Comparison objects to a TSV file."""

    with open(output_path, "w", newline="", encoding="utf-8") as file:
        writer = csv.writer(file, delimiter="\t")

        # Write column headers
        writer.writerow(["name1", "name2", "score", "true"])
        # Loop through Comparison objects and write each row
        for i, comparison in enumerate(comparisons, start=1):
            writer.writerow([
                comparison.name1,
                comparison.name2,
                comparison.score,
                comparison.true
            ])
            if (i % 10000 == 0):
                logger.info(f"{i} Pairs Processed")

# 80/20 test split generation
def split_save_data():
    df = pd.read_csv(
        "data/annotated-index.tsv",
        sep="\t",
        header=None,
        names=["name1", "name2", "true"] # Add header row because it did not have one already
    )

    # Ensure header worked
    # print(df.columns.tolist())

    # Need to conver to list for python train_test plit
    unique_name = df['name1'].unique().tolist()

    train_df, test_df = train_test_split(
        unique_name, test_size=0.2, random_state=42
    )

    # Assign to the dfs
    train_df = df[df["name1"].isin(train_df)]
    test_df = df[df["name1"].isin(test_df)]

    # Reduce datasets to 10% each (reduce computational expenses)
    train_df = train_df.sample(frac=0.1, random_state=42)
    test_df = test_df.sample(frac=0.1, random_state=42)

    # Check to make sure it has split correctly
    print("Total unique names:", len(unique_name))
    print("Training unique names:", train_df["name1"].nunique())
    print("Testing unique names:", test_df["name1"].nunique())

    # Save to tsv
    train_df.to_csv('data/annotated-index-train.tsv', sep='\t', index=False)
    test_df.to_csv('data/annotated-index-test.tsv', sep='\t', index=False)

def check_threshold(model):
    # Run on training to get correct threshold
    comparisons = TsvIterator("data/annotated-index-train.tsv", model)
    save_results(comparisons, f"results_{model.__name__}_train.tsv")
    train_results = pd.read_csv(f"results_{model.__name__}_train.tsv", sep="\t")

    # Precision and recall curve
    precision, recall, thresholds = precision_recall_curve(
        train_results["true"],
        train_results["score"]
    )

    # This part was generated by ChatGPT as an additional metric
    f1 = 2 * (precision[:-1] * recall[:-1]) / (
        precision[:-1] + recall[:-1] + 1e-10
    )


    # Plot and remove last row so that the lengths are even with threshold
    plt.plot(thresholds, precision[:-1], label="Precision")
    plt.plot(thresholds, recall[:-1], label="Recall")

    plt.xlabel(f"{model.__name__} Similarity Threshold")
    plt.ylabel("Score")
    plt.title(f"{model.__name__} Precision and Recall vs. Threshold")
    plt.plot(thresholds, f1, label="F1")

    plt.ylim(0, 1)
    plt.legend()
    plt.show()

def parallel(row, model):
    name1 = row[0]
    name2 = row[1]
    true = int(row[2])
    matcher = model(name1, name2)
    score = matcher.score(name1,name2)
    return Comparison(row[0], row[1], score, true) 

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Name Matcher")
    parser.add_argument("-f", "--file", required=True, help="path to dataset")
    parser.add_argument("-s", "--scoring", choices = ["exact","jaccard", "levenshtein", "tfidf", "jaro"], required=True, help="scoring algorithm")
    parser.add_argument("-t", "--threshold", type=float, default=0.5, help="similarity threshold")
    parser.add_argument("-e", "--evaluate", help = "flag whether to evaluate", action= "store_true")
    parser.add_argument("--plot", action="store_true", help="Display precision, recall, and F1 versus threshold")
    parser.add_argument("-p", "--parallel", help = "flag whether to parallelize", action= "store_true")
    args = parser.parse_args()

    # Adding logging
    logger = logging.getLogger("NameMatcher")
    logger.setLevel(logging.DEBUG)

    file_handler = logging.FileHandler("logs.txt", mode = "w")
    logger.addHandler(file_handler)

    models = {
    "exact": ExactMatch,
    "jaccard": Jaccard,
    "levenshtein": LevenshteinScore,
    "tfidf": Tfidf_matcher,
    "jaro": Jarowinkler
    }

    # Match input to a model class
    model = models[args.scoring]

    logger.info("Split data into training and test sets")
    # Split the data
    split_save_data()


    if model == Tfidf_matcher:
        logger.info("TFIDF vectorization")
        vector = Tfidf_matcher()
        train = pd.read_csv(f"data/annotated-index-train.tsv", sep="\t")
        train = train["name1"]
        fitting = vector.fit_vector(train)

    # Plot to find best threshold
    if args.plot and model != ExactMatch:
        check_threshold(model)

    elif args.parallel:
        start_time = time.time()  # Record start time
        threshold = args.threshold
        logger.info(f"Starting {model.__name__} scoring")
        # Read file
        with open(args.file, newline="", encoding="utf-8") as file:
            rows = csv.reader(file, delimiter='\t')
            next(rows) # skip header
            pool_args = [(row, model) for row in rows]
        with Pool(4) as pool:
            results = pool.starmap(parallel, pool_args)
        save_results(results, f"data/results_{args.scoring}.tsv")
        results = pd.read_csv(f"data/results_{args.scoring}.tsv", sep="\t")
        logger.info(f"{model.__name__} scoring has finished")
        results["predicted"] = (results["score"] >= threshold).astype(int)
        end_time = time.time()    # Record end time
        print(f"Parallel execution time: {end_time - start_time} seconds")
            
    else:
        start_time = time.time()  # Record start time
        threshold = args.threshold

        # Run scoring algorithm
        logger.info(f"Starting {model.__name__} scoring")
        comparisons = TsvIterator(args.file, model)
        save_results(comparisons, f"data/results_{args.scoring}.tsv")
        logger.info(f"{model.__name__} scoring has finished")
        # Load results to dataframe for evaluation
        results = pd.read_csv(f"data/results_{args.scoring}.tsv", sep="\t")
        results["predicted"] = (results["score"] >= threshold).astype(int)
        end_time = time.time()    # Record end time
        print(f"Normal execution time: {end_time - start_time} seconds")


    # Print/Evaluate
    if args.evaluate:
        print(f"{args.scoring} Results:\n")
        print("Precision:", evaluate(results, "precision"))
        print("Recall:", evaluate(results, "recall"))
        print("F1:", evaluate(results, "f1"))